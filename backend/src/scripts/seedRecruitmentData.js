async function seedData() {
  console.log('=== Seeding 10 Jobs Per Recruiter (Total 50 Jobs Across 5 Recruiters) ===\n');
  const now = new Date();
  const passwordHash = await bcrypt.hash(DEFAULT_PASSWORD, 12);

  let totalJobsInScript = 0;

  for (let rIdx = 0; rIdx < RECRUITERS.length; rIdx++) {
    const rData = RECRUITERS[rIdx];
    const cleanEmail = rData.email.trim().toLowerCase();

    // Find or create recruiter user
    const user = await prisma.user.upsert({
      where: { email: cleanEmail },
      update: {
        fullName: rData.fullName,
        passwordHash,
        role: 'recruiter',
        status: 'active',
        emailVerifiedAt: now,
      },
      create: {
        email: cleanEmail,
        fullName: rData.fullName,
        passwordHash,
        role: 'recruiter',
        status: 'active',
        emailVerifiedAt: now,
      },
    });

    console.log(`\n[Recruiter ${rIdx + 1}/5] ${user.fullName} (${user.email})`);

    // Find or create company
    const compData = rData.company;
    let company = await prisma.company.findFirst({
      where: { name: compData.name },
    });

    if (company) {
      company = await prisma.company.update({
        where: { id: company.id },
        data: {
          ...compData,
          ownerId: user.id,
          status: 'APPROVED',
          approvedAt: now,
        },
      });
    } else {
      company = await prisma.company.create({
        data: {
          ...compData,
          ownerId: user.id,
          status: 'APPROVED',
          approvedAt: now,
          submittedAt: now,
        },
      });
    }

    // Ensure CompanyMembership
    await prisma.companyMembership.upsert({
      where: {
        companyId_userId: {
          companyId: company.id,
          userId: user.id,
        },
      },
      update: {
        role: 'OWNER',
        membershipStatus: 'ACTIVE',
      },
      create: {
        companyId: company.id,
        userId: user.id,
        role: 'OWNER',
        membershipStatus: 'ACTIVE',
      },
    });

    // Ensure RecruiterProfile
    await prisma.recruiterProfile.upsert({
      where: { userId: user.id },
      update: {
        companyId: company.id,
        phone: rData.phone,
        designation: rData.designation,
        linkedinUrl: rData.linkedinUrl,
      },
      create: {
        userId: user.id,
        companyId: company.id,
        phone: rData.phone,
        designation: rData.designation,
        linkedinUrl: rData.linkedinUrl,
      },
    });

    console.log(`  Processing ${rData.jobs.length} jobs for "${company.name}"...`);

    for (let jIdx = 0; jIdx < rData.jobs.length; jIdx++) {
      const jobData = rData.jobs[jIdx];
      totalJobsInScript++;
      const deadline = new Date(Date.now() + 60 * 24 * 60 * 60 * 1000);

      const contentHash = computeJobHash({
        title: jobData.title,
        employmentType: jobData.employmentType,
        workMode: jobData.workMode,
        city: jobData.city,
        country: jobData.country,
        description: jobData.description,
      });

      const applicationQuestions = [
        {
          id: `q_exp_${jIdx + 1}`,
          type: 'SHORT_TEXT',
          question: 'How many years of relevant experience do you have with the required tech stack?',
          required: true,
          options: [],
        },
        {
          id: `q_notice_${jIdx + 1}`,
          type: 'SHORT_TEXT',
          question: 'What is your current notice period / earliest availability to join?',
          required: true,
          options: [],
        },
        {
          id: `q_portfolio_${jIdx + 1}`,
          type: 'SHORT_TEXT',
          question: 'Please share your GitHub, portfolio, or recent technical projects link.',
          required: false,
          options: [],
        },
      ];

      const existingJob = await prisma.job.findFirst({
        where: {
          companyId: company.id,
          title: jobData.title,
        },
      });

      if (existingJob) {
        await prisma.job.update({
          where: { id: existingJob.id },
          data: {
            ...jobData,
            companyId: company.id,
            createdById: user.id,
            updatedById: user.id,
            contactEmail: cleanEmail,
            applicationDeadline: deadline,
            allowAfterDeadline: false,
            requireResume: true,
            requireCoverLetter: false,
            maxApplications: 300,
            applicationQuestions,
            status: 'PUBLISHED',
            moderationStatus: 'CLEARED',
            moderationScore: 0,
            moderationFlags: [],
            contentHash,
            publishedAt: now,
            submittedAt: now,
          },
        });
        console.log(`    [Job ${jIdx + 1}/10] Ready (Updated): "${jobData.title}"`);
      } else {
        await prisma.job.create({
          data: {
            ...jobData,
            companyId: company.id,
            createdById: user.id,
            updatedById: user.id,
            contactEmail: cleanEmail,
            applicationDeadline: deadline,
            allowAfterDeadline: false,
            requireResume: true,
            requireCoverLetter: false,
            maxApplications: 300,
            applicationQuestions,
            status: 'PUBLISHED',
            moderationStatus: 'CLEARED',
            moderationScore: 0,
            moderationFlags: [],
            contentHash,
            publishedAt: now,
            submittedAt: now,
          },
        });
        console.log(`    [Job ${jIdx + 1}/10] Ready (Created): "${jobData.title}"`);
      }
    }
  }

  console.log('\n======================================================');
  console.log('              ALL 50 JOBS SEEDED SUCCESSFULLY         ');
  console.log('======================================================');
  for (const r of RECRUITERS) {
    const count = await prisma.job.count({
      where: {
        createdBy: { email: r.email },
        status: 'PUBLISHED',
      },
    });
    console.log(`${r.fullName} (${r.company.name}): ${count} published jobs`);
  }
  const totalPublished = await prisma.job.count({ where: { status: 'PUBLISHED' } });
  console.log(`Total Published Jobs in System: ${totalPublished}`);
  console.log('======================================================\n');
}

seedData()
  .catch((err) => {
    console.error('Seeding error:', err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
